export const WATER_BLOCKS = Object.freeze([BLOCK.WATER, BLOCK.WATER_1, BLOCK.WATER_2, BLOCK.WATER_3, BLOCK.WATER_4, BLOCK.WATER_5, BLOCK.WATER_6, BLOCK.WATER_7]);
export const LAVA_BLOCKS = Object.freeze([BLOCK.LAVA, BLOCK.LAVA_1, BLOCK.LAVA_2, BLOCK.LAVA_3, BLOCK.LAVA_4, BLOCK.LAVA_5, BLOCK.LAVA_6, BLOCK.LAVA_7]);

export const isWaterBlock = (id) => WATER_BLOCKS.includes(id);
export const isLavaBlock = (id) => LAVA_BLOCKS.includes(id);
export const isLiquidBlock = (id) => isWaterBlock(id) || isLavaBlock(id);
export const fluidKind = (id) => isWaterBlock(id) ? 'water' : isLavaBlock(id) ? 'lava' : null;
export const fluidLevel = (id) => isWaterBlock(id) ? WATER_BLOCKS.indexOf(id) : isLavaBlock(id) ? LAVA_BLOCKS.indexOf(id) : null;
export const fluidBlock = (kind, level = 0) => (kind === 'water' ? WATER_BLOCKS : kind === 'lava' ? LAVA_BLOCKS : [BLOCK.AIR])[Math.max(0, Math.min(7, Math.round(level)))] ?? BLOCK.AIR;
export const fluidSurfaceHeight = (id) => {
  const level = fluidLevel(id);
  return level == null ? 0 : 0.88 - level * 0.1;
};
