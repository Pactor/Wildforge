export function faceShade(id, faceNormalY = 0) {
  let shade = faceNormalY > 0 ? 1.08 : faceNormalY < 0 ? 0.7 : 0.86;
  if (isWaterBlock(id)) shade *= 1.08;
  if (isLavaBlock(id)) shade *= 1.2;
  return [shade, shade, shade];
}

export function blockTexture(id, faceNormalY = 0) {
  const texture = BLOCKS[id]?.texture ?? 0;
  if (typeof texture === 'number') return texture;
  if (faceNormalY > 0) return texture.top;
  if (faceNormalY < 0) return texture.bottom;
  return texture.side;
}
